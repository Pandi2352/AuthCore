#!/usr/bin/env node
// Builds src/config/emoji-icons.ts: the navigation icons in Microsoft's Fluent Emoji (flat)
// style, for the "Emoji" icon style (theme appearance.icons).
//
//   npm run icons:emoji
//
// Only the icons the app uses are copied (a few KB) from the dev dependency
// @iconify-json/fluent-emoji-flat (MIT, © Microsoft — github.com/microsoft/fluentui-emoji),
// so the app never ships the full set (3 000+ icons, several MB).
// Add an icon: add its IconName (src/config/icons.ts) → Fluent Emoji name below, run the script.
// Names: https://icon-sets.iconify.design/fluent-emoji-flat/
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/fluent-emoji-flat/icons.json');
const info = require('@iconify-json/fluent-emoji-flat/info.json');

/** IconName (src/config/icons.ts) → Fluent Emoji icon. */
const MAP = {
  Activity: 'chart-increasing',
  Bell: 'bell',
  Building2: 'office-building',
  CircleHelp: 'red-question-mark',
  ExternalLink: 'link',
  FileText: 'page-facing-up',
  FolderTree: 'card-index-dividers',
  HardDrive: 'file-cabinet',
  History: 'mantelpiece-clock',
  KeyRound: 'key',
  LayoutDashboard: 'bar-chart',
  Layers: 'package',
  ListTree: 'clipboard',
  Lock: 'locked',
  MailPlus: 'envelope-with-arrow',
  Monitor: 'desktop-computer',
  MonitorSmartphone: 'laptop',
  Moon: 'crescent-moon',
  Palette: 'artist-palette',
  Search: 'magnifying-glass-tilted-left',
  Settings: 'gear',
  Shield: 'shield',
  ShieldCheck: 'locked-with-key',
  SlidersHorizontal: 'control-knobs',
  Sun: 'sun',
  UserPlus: 'identification-card',
  UserRound: 'person',
  Users: 'people-hugging',
};

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'src/config/emoji-icons.ts');

const lines = [];
for (const [iconName, emoji] of Object.entries(MAP)) {
  const icon = set.icons[emoji];
  if (!icon) {
    console.error(`Unknown Fluent Emoji icon "${emoji}" (for ${iconName})`);
    process.exit(1);
  }
  const size = `${icon.width ?? set.width ?? 32}`;
  lines.push(`  ${iconName}: { body: ${JSON.stringify(icon.body)}, size: ${size} },`);
}

const source = `// GENERATED by scripts/build-emoji-icons.mjs — do not edit by hand (npm run icons:emoji).
// ${info.name}: © ${info.author.name}, ${info.license.title} licence — ${info.author.url}

import type { IconName } from './icons';

export interface EmojiIcon {
  /** SVG content (paths with their own colors). */
  body: string;
  /** Square viewBox size. */
  size: number;
}

/**
 * Loaded on demand (only for the "emoji" icon style) — keep it out of eager imports; use
 * useEmojiIcons() in app/layouts/sidebar. Every IconName needs an entry (type-checked).
 */
export const emojiIcons = {
${lines.join('\n')}
} satisfies Record<IconName, EmojiIcon>;
`;
fs.writeFileSync(OUT, source);
console.log(
  `Wrote ${path.relative(ROOT, OUT)} (${Object.keys(MAP).length} icons, ${(source.length / 1024).toFixed(1)} KB)`,
);
